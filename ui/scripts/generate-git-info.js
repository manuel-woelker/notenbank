import { execSync } from 'child_process'
import { writeFileSync, existsSync } from 'fs'
import { fileURLToPath } from 'url'
import { dirname, join } from 'path'

const __filename = fileURLToPath(import.meta.url)
const __dirname = dirname(__filename)

// Try to find git executable in common paths
const findGitCommand = () => {
  const possiblePaths = [
    'git', // If git is in PATH
    'C:\\Program Files\\Git\\cmd\\git.exe',
    'C:\\Program Files (x86)\\Git\\cmd\\git.exe',
  ]

  for (const gitPath of possiblePaths) {
    try {
      execSync(`"${gitPath}" --version`, { encoding: 'utf8', stdio: 'ignore' })
      return gitPath
    } catch {
      continue
    }
  }
  return null
}

const gitCommand = findGitCommand()

const getGitCommitHash = () => {
  if (!gitCommand) return 'dev'
  try {
    return execSync(`"${gitCommand}" rev-parse --short HEAD`, { encoding: 'utf8' }).trim()
  } catch {
    return 'dev'
  }
}

const getGitCommitDate = () => {
  if (!gitCommand) return new Date().toISOString().split('T')[0]
  try {
    return execSync(`"${gitCommand}" log -1 --format=%cd --date=short`, { encoding: 'utf8' }).trim()
  } catch {
    return new Date().toISOString().split('T')[0]
  }
}

const getGitCommitMessage = () => {
  if (!gitCommand) return 'Development build'
  try {
    return execSync(`"${gitCommand}" log -1 --format=%s`, { encoding: 'utf8' }).trim()
  } catch {
    return 'Development build'
  }
}

const gitInfo = {
  commitHash: getGitCommitHash(),
  commitDate: getGitCommitDate(),
  commitMessage: getGitCommitMessage(),
}

const output = `// This file is auto-generated by scripts/generate-git-info.js
export const GIT_INFO = ${JSON.stringify(gitInfo, null, 2)}
`

writeFileSync(join(__dirname, '../src/git-info.ts'), output)
console.log('Git info generated:', gitInfo)
